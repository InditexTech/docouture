#!/usr/bin/env node
//
// Assemble `src/img/ids-icons.svg` from the manifest and the local mirror.
//
// Offline and instant: adding an icon is one line in `src/img/icons.yml` plus a
// run of this script. The network stage is `fetch-icons`, run only when the
// design system catalogue itself needs refreshing.
//
// The generated sprite is committed. It is the artifact the bundle ships and
// the thing a reviewer can actually see change; the mirror it is cut from is
// gitignored scratch.
//
// Usage:
//   node scripts/build-sprite.mjs            write src/img/ids-icons.svg
//   node scripts/build-sprite.mjs --check    verify it is up to date, write nothing

import { readFile, writeFile } from 'node:fs/promises'
import { glob } from 'node:fs/promises'
import { join, relative } from 'node:path'

import { optimize } from 'svgo'

import svgoConfig from '../gulp.d/lib/svgo-config.js'
import { fail, loadManifest, loadMasks, paths, readMirror, style, suggest } from './lib/icons.mjs'

// Attribution travels inside the file, not in a comment: svgo's preset-default
// strips comments, and this sprite is optimized twice — here, and again by the
// asset pipeline when the bundle is packed. `<desc>` survives both because
// removeDesc is disabled in gulp.d/lib/svgo-config.js, which is exactly how the
// octicons sprite carries its MIT notice.
const TITLE = 'IOP Design System icons'
const DESC =
  'IOP Design System icons - (C) Industria de Diseno Textil, S.A. - ' +
  'License: INDITEX, proprietary, internal use only - ' +
  'Source: https://amgassets.inditex.com/amigaweb/icons/ - ' +
  'Generated by scripts/build-sprite.mjs from src/img/icons.yml; see icons.lock.json. Do not edit.'

/** Report every unresolvable manifest entry at once, with suggestions, then stop. */
function resolve(entries, index) {
  const symbols = []
  const missing = []

  for (const { group, name, id } of entries) {
    const markup = index.get(group)?.get(name)
    if (markup) symbols.push({ id, markup })
    else missing.push({ group, name, suggestions: suggest(index, group, name) })
  }

  if (missing.length) {
    const lines = missing.map(({ group, name, suggestions }) => {
      const hint = suggestions.length ? `\n    did you mean: ${suggestions.join(', ')}?` : ''
      return `  ${style.red}✗${style.off} ${group}/${name} not found in group "${group}"${hint}`
    })
    throw new Error(
      `${missing.length} icon(s) in src/img/icons.yml do not exist:\n${lines.join('\n')}\n` +
        '\nGroup names are not intuitive — try `just icons-search <term>`.'
    )
  }

  return symbols
}

const escape = (text) => text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')

function render(symbols) {
  return [
    '<svg xmlns="http://www.w3.org/2000/svg" width="0" height="0" style="display:none">',
    `  <title>${escape(TITLE)}</title>`,
    `  <desc>${escape(DESC)}</desc>`,
    ...symbols.map(({ markup }) => `  ${markup}`),
    '</svg>',
    '',
  ].join('\n')
}

// ------------------------------------------------------------- icon masks -----
//
// Asciidoctor's own admonition markup (`icons: font`, both playbooks) is fixed
// — `<i class="fa icon-note" title="Note">` — leaving no room for the
// `{{icon}}` helper's `<svg><use>`. A `mask-image` data URI is the only way to
// get one of these vendored icons onto that markup, coloured with
// `background: currentColor` so it still inverts for free under the dark
// theme, same as every `.ids-icon` does through `color: inherit`. See GH-13
// and src/img/icons.yml's own `masks:` header comment.
//
// The same constraint binds anything an Asciidoctor EXTENSION emits: it runs
// at conversion time, with no `uiRootPath`, so it cannot address the sprite
// either. Those consumers want a class rather than a bare custom property —
// they have no stylesheet of their own to declare `mask-image` in — hence the
// `.ids-icon-mask--<group>-<name>` utilities generated alongside the
// properties. `[card,icon=…]` (GH-20) is the first.

const MASKS_HEADER = `/*
 * IOP Design System icon masks — a second, CSS-consumable form of a subset of
 * the icons in ids-icons.svg, for markup that has no room for an <svg><use>:
 * admonitions (doc.css, GH-13) and anything an Asciidoctor extension emits
 * (GH-20), which has no uiRootPath to address the sprite with.
 *
 * Generated by scripts/build-sprite.mjs from src/img/icons.yml's \`masks:\`
 * list; see icons.lock.json for provenance of the source sprites. Do not edit
 * by hand — edits are overwritten by the next \`just icons-build\`.
 *
 * ${DESC}
 *
 * Each custom property is a \`mask-image\`-ready data URI. The path's own fill
 * is irrelevant beyond being opaque — \`mask-image\` reads alpha (or luminance
 * where alpha masking isn't supported), never colour — so consumers set the
 * visible colour with \`background: currentColor\` on the masked element.
 *
 * The \`.ids-icon-mask--*\` utilities below carry the mask and nothing else:
 * size and colour stay with the consumer, because an icon slot's dimensions
 * belong to the component it sits in, not to the icon.
 */
`

// Symbol content carries `fill="currentColor"`, meaningful inside the live DOM
// (icons.css's own .ids-icon rule) but meaningless inside a standalone data
// URI with no element to inherit from — swapped for an opaque literal so every
// browser's mask reliably sees full alpha.
const MASK_FILL = '#000'

// Percent-encoding a data URI by hand (rather than encodeURIComponent, which
// escapes far more than CSS's url() needs and produces a noisier diff) — only
// the characters that would otherwise break out of `url("...")` or confuse a
// browser's data URI parser.
const encodeDataUri = (svg) =>
  svg
    .replace(/"/g, "'")
    .replace(/%/g, '%25')
    .replace(/#/g, '%23')
    .replace(/</g, '%3C')
    .replace(/>/g, '%3E')
    .replace(/\n/g, '')

function maskDataUri(markup) {
  const viewBox = markup.match(/\bviewBox="([^"]+)"/)?.[1]
  if (!viewBox) throw new Error(`Symbol has no viewBox, can't be rendered as a standalone mask: ${markup}`)

  const inner = markup
    .replace(/^<symbol\b[^>]*>/, '')
    .replace(/<\/symbol>$/, '')
    .replace(/currentColor/g, MASK_FILL)

  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}">${inner}</svg>`
  const { data: optimized } = optimize(svg, svgoConfig)
  return `url("data:image/svg+xml,${encodeDataUri(optimized)}")`
}

function renderMasks(entries, index) {
  const missing = []
  const props = []
  const utilities = []

  for (const { group, name } of entries) {
    const markup = index.get(group)?.get(name)
    if (!markup) {
      missing.push({ group, name, suggestions: suggest(index, group, name) })
      continue
    }
    props.push(`  --icon-mask-${group}-${name}: ${maskDataUri(markup)};`)
    utilities.push(
      `.ids-icon-mask--${group}-${name} {\n  mask-image: var(--icon-mask-${group}-${name});\n}`
    )
  }

  if (missing.length) {
    const lines = missing.map(({ group, name, suggestions }) => {
      const hint = suggestions.length ? `\n    did you mean: ${suggestions.join(', ')}?` : ''
      return `  ${style.red}✗${style.off} ${group}/${name} not found in group "${group}"${hint}`
    })
    throw new Error(`${missing.length} mask icon(s) in src/img/icons.yml do not exist:\n${lines.join('\n')}`)
  }

  return [MASKS_HEADER, ':root {', ...props, '}', '', utilities.join('\n\n'), ''].join('\n')
}

// `{{icon "group" "name"}}`, with or without trailing hash arguments.
const USAGE_RX = /\{\{\s*icon\s+"([a-z0-9-]+)"\s+"([a-z0-9-]+)"/g

/**
 * Report every icon reference a source tree makes that the given set does not
 * contain, as one error naming all of them and where they came from.
 */
function reportUnresolved(unresolved, what, listedUnder) {
  if (!unresolved.size) return

  const lines = [...unresolved].map(
    ([ref, files]) => `  ${style.red}✗${style.off} ${ref} ${style.dim}(used in ${files.join(', ')})${style.off}`
  )
  throw new Error(
    `${unresolved.size} icon(s) used by ${what} are not in src/img/icons.yml's \`${listedUnder}:\`:\n${lines.join('\n')}\n` +
      '\nAdd them to the manifest and run `just icons-build` again.'
  )
}

/**
 * Fail if a template uses an icon the manifest does not vendor.
 *
 * The helper cannot check this: it runs inside Antora, long after the sprite is
 * built, and a missing symbol degrades to an invisible `<use>` rather than an
 * error. Catching it here keeps "the icon silently does not render" out of the
 * possible outcomes.
 */
async function checkTemplateUsage(vendored) {
  const unresolved = new Map()

  for (const dir of ['src/layouts', 'src/partials']) {
    for await (const file of glob(join(paths.packageRoot, dir, '**/*.hbs'))) {
      const source = await readFile(file, 'utf8')
      for (const [, group, name] of source.matchAll(USAGE_RX)) {
        const ref = `${group}/${name}`
        if (vendored.has(ref)) continue
        if (!unresolved.has(ref)) unresolved.set(ref, [])
        unresolved.get(ref).push(relative(paths.packageRoot, file))
      }
    }
  }

  reportUnresolved(unresolved, 'templates', 'icons')
}

// `[card,icon="group/name"]`, anywhere in the block attribute list, quoted or
// bare. Deliberately loose about what surrounds it: this is a lint, and a
// missed reference costs a rebuild, while a false positive costs a build.
const CARD_ICON_RX = /^\[card[^\]\n]*\bicon=(?:"([^"]+)"|'([^']+)'|([^,\]\s]+))/gm

/**
 * Fail if a page asks `[card,icon=…]` for an icon that has no mask.
 *
 * Same reasoning as the template check, one step further out: the `[card]`
 * block (asciidoc-extensions/lib/card-grid.js) runs inside Antora with no
 * uiRootPath, so it emits an `.ids-icon-mask--*` class and cannot verify the
 * mask exists. icons.yml is the single source of truth for that, and this is
 * where it gets enforced — rather than duplicating the mask list into the
 * extension package, where it would drift.
 *
 * Reaches sideways into the sibling site packages, which is unusual for this
 * script and bounded on purpose: it can only see content that lives in this
 * repository. A downstream site consuming the published packages gets no such
 * check, which is why card-grid.css falls back to a visible marker for an
 * unmasked icon rather than rendering an empty box.
 */
async function checkCardIconUsage(masked) {
  const unresolved = new Map()
  const roots = [
    join(paths.packageRoot, 'preview-src'),
    join(paths.packageRoot, '../example/docs'),
    join(paths.packageRoot, '../starter/docs'),
  ]

  for (const root of roots) {
    for await (const file of glob(join(root, '**/*.adoc'))) {
      const source = await readFile(file, 'utf8')
      for (const [, quoted, single, bare] of source.matchAll(CARD_ICON_RX)) {
        const ref = quoted ?? single ?? bare
        if (masked.has(ref)) continue
        if (!unresolved.has(ref)) unresolved.set(ref, [])
        unresolved.get(ref).push(relative(paths.packageRoot, file))
      }
    }
  }

  reportUnresolved(unresolved, '[card,icon=…]', 'masks')
}

/** Compare a generated artifact against what's on disk and either write it or report drift. */
async function sync(path, content, { check }) {
  const rel = relative(paths.packageRoot, path)
  let previous
  try {
    previous = await readFile(path, 'utf8')
  } catch (err) {
    if (err.code !== 'ENOENT') throw err
    previous = null
  }

  if (check) {
    if (previous === content) {
      console.log(`${style.green}✓${style.off} ${rel} is up to date`)
      return
    }
    console.error(`${style.red}✗${style.off} ${rel} is stale. Run \`just icons-build\` and commit the result.`)
    process.exitCode = 1
    return
  }

  await writeFile(path, content)
  const bytes = Buffer.byteLength(content)
  const delta = previous === null ? null : bytes - Buffer.byteLength(previous)
  const deltaText = delta === null ? 'new' : delta === 0 ? 'unchanged' : `${delta > 0 ? '+' : ''}${delta} B`
  console.log(`${style.green}✓${style.off} ${rel} ${style.dim}(${bytes} B, ${deltaText})${style.off}`)
}

async function main() {
  const check = process.argv.includes('--check')

  const entries = await loadManifest()
  const maskEntries = await loadMasks()
  // The manifest only names a handful of groups, but the whole mirror is loaded
  // so a wrong-group name can be suggested from the full catalogue — the most
  // common mistake by far.
  const index = await readMirror()
  const symbols = resolve(entries, index)

  await checkTemplateUsage(new Set(entries.map(({ group, name }) => `${group}/${name}`)))
  await checkCardIconUsage(new Set(maskEntries.map(({ group, name }) => `${group}/${name}`)))

  const { data: sprite } = optimize(render(symbols), { path: paths.sprite, ...svgoConfig })

  // Guard the two svgo behaviours this file depends on. The sprite's children
  // sit inside a `display:none` wrapper, which removeHiddenElems would strip,
  // and the licence notice lives in a `<desc>`, which removeDesc would strip.
  const kept = (sprite.match(/<symbol\b/g) ?? []).length
  if (kept !== symbols.length) {
    throw new Error(
      `svgo emitted ${kept} of ${symbols.length} symbols — check removeHiddenElems in gulp.d/lib/svgo-config.js`
    )
  }
  if (!sprite.includes('INDITEX')) {
    throw new Error('svgo dropped the licence <desc> — check removeDesc in gulp.d/lib/svgo-config.js')
  }

  await sync(paths.sprite, sprite, { check })

  const masks = renderMasks(maskEntries, index)
  await sync(paths.masks, masks, { check })
}

main().catch(fail)
